    private fun blueprintJson(
        concept: String,
        vararg children: Pair<String, String>,
        properties: Map<String, String> = emptyMap(),
        references: Map<String, String> = emptyMap(),
    ): String {
        val parts = mutableListOf(""""concept":"$concept"""")
        if (properties.isNotEmpty()) parts.add(""""properties":[${properties.entries.joinToString(",") { """{"name":"${it.key}","value":"${it.value}"}""" }}]""")
        if (references.isNotEmpty()) parts.add(""""references":[${references.entries.joinToString(",") { """{"role":"${it.key}","target":"${it.value}"}""" }}]""")
        if (children.isNotEmpty()) parts.add(""""children":[${children.joinToString(",") { (role, node) -> """{"role":"$role","nodes":[$node]}""" }}]""")
        return parts.joinToString(",", "{", "}")
    }

    /** The content of a template declaration: a fragment `{ return; }` where the `return;` is repeated once per ancestor of the matched Thing. */
    private val loopedFragment: String by lazy {
        val ancestors = blueprintJson(
            "jetbrains.mps.baseLanguage.structure.StatementList",
            "statement" to blueprintJson(
                "jetbrains.mps.baseLanguage.structure.ExpressionStatement",
                "expression" to blueprintJson(
                    "jetbrains.mps.baseLanguage.structure.DotExpression",
                    "operand" to blueprintJson("jetbrains.mps.lang.generator.structure.TemplateFunctionParameter_sourceNode"),
                    "operation" to blueprintJson("jetbrains.mps.lang.smodel.structure.Node_GetAncestorsOperation"),
                ),
            ),
        )
        val loop = blueprintJson(
            "jetbrains.mps.lang.generator.structure.LoopMacro",
            "sourceNodesQuery" to blueprintJson("jetbrains.mps.lang.generator.structure.SourceSubstituteMacro_SourceNodesQuery", "body" to ancestors),
        )
        blueprintJson(
            "jetbrains.mps.baseLanguage.structure.BlockStatement",
            "statements" to blueprintJson(
                "jetbrains.mps.baseLanguage.structure.StatementList",
                "statement" to blueprintJson("jetbrains.mps.baseLanguage.structure.ReturnStatement", "smodelAttribute" to loop),
            ),
            "smodelAttribute" to blueprintJson("jetbrains.mps.lang.generator.structure.TemplateFragment"),
        )
    }

    /**
     * A fresh language with a generator: a concept `Thing` extending BaseLanguage's `Statement`, and one mapping
     * configuration whose reduction rule turns a `Thing` into a statement. Not built yet.
     *
     * The template is an inline `return;`, or with [loop] a template declaration the rule calls: a fragment
     * `{ return; }` whose `return;` carries a `$LOOP$` over the Thing's ancestors. With [compiled] the generator has
     * `generateTemplates=true`, so a make compiles its templates into Java classes that run in place of the template nodes.
     */
    private inner class ReductionFixture(compiled: Boolean = false, loop: Boolean = false) {
        val languageName = "test.trace${System.nanoTime()}"
        val language: Language
        val generatorName: String
        val generatorModelName: String
        val ruleRef: String
        val mappingConfigurationRef: String

        init {
            val dir = createDirInProject(languageName)
            var created: Language? = null
            executeCommand { created = LanguageProducer(myProject).withGenerator(true).create(languageName, dir) }
            language = checkNotNull(created)
            val structureRef = readOnRepo { modelRefOf(language.models.single { it.name.longName.endsWith(".structure") }) }
            val generatorModel = readOnRepo { language.generators.single().models.single { SModelStereotype.isGeneratorModel(it) } }
            generatorName = readOnRepo { language.generators.single().moduleName!! }
            generatorModelName = readOnRepo { generatorModel.name.value }
            expectOk(runTool {
                it.mps_mcp_alter_structure(
                    MPSStructureAlterOperation.CREATE_CONCEPTS,
                    """{"structureModelRef":"$structureRef","conceptsJson":[{"name":"Thing","extends":"jetbrains.mps.baseLanguage.structure.Statement"}]}""",
                )
            })
            val thingRef = readOnRepo {
                val model = PersistenceFacade.getInstance().createModelReference(structureRef).resolve(myProject.repository)!!
                PersistenceFacade.getInstance().asString(model.rootNodes.single { it.name == "Thing" }.reference)
            }
            val consequence = if (loop) {
                val declaration = expectOk(runTool(JetBrainsMPSRootNodeMcpToolset()) {
                    it.mps_mcp_insert_root_node_from_json(
                        modelRefOf(generatorModel),
                        JsonOrText(blueprintJson("jetbrains.mps.lang.generator.structure.TemplateDeclaration", "contentNode" to loopedFragment, properties = mapOf("name" to "looped"))),
                        dryRun = false,
                        responseDetail = "summary",
                    )
                })
                val declarationRef = declaration.getAsJsonArray("roots").single().asJsonObject.get("reference").asString
                blueprintJson("jetbrains.mps.lang.generator.structure.TemplateDeclarationReference", references = mapOf("template" to declarationRef))
            } else {
                blueprintJson(
                    "jetbrains.mps.lang.generator.structure.InlineTemplate_RuleConsequence",
                    "templateNode" to blueprintJson("jetbrains.mps.baseLanguage.structure.ReturnStatement"),
                )
            }
            val inserted = expectOk(runTool(JetBrainsMPSRootNodeMcpToolset()) {
                it.mps_mcp_insert_root_node_from_json(
                    modelRefOf(generatorModel),
                    JsonOrText(
                        """{"concept":"jetbrains.mps.lang.generator.structure.MappingConfiguration","properties":[{"name":"name","value":"main"}],
                           "children":[{"role":"reductionMappingRule","nodes":[{"concept":"jetbrains.mps.lang.generator.structure.Reduction_MappingRule",
                             "references":[{"role":"applicableConcept","target":"$thingRef"}],
                             "children":[{"role":"ruleConsequence","nodes":[$consequence]}]}]}]}""",
                    ),
                    dryRun = false,
                    responseDetail = "summary",
                )
            })
            if (compiled) {
                executeCommand {
                    val generator = language.generators.single()
                    val descriptor = generator.moduleDescriptor
                    descriptor.isGenerateTemplates = true
                    generator.setModuleDescriptor(descriptor)
                }
            }
            mappingConfigurationRef = inserted.getAsJsonArray("roots").single().asJsonObject.get("reference").asString
            ruleRef = readOnRepo {
                val root = PersistenceFacade.getInstance().createNodeReference(mappingConfigurationRef).resolve(myProject.repository)!!
                PersistenceFacade.getInstance().asString(root.children.single { it.concept.name == "Reduction_MappingRule" }.reference)
            }
        }
    }
