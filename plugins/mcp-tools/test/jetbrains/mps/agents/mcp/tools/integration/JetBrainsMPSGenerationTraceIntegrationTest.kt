/**
 * `mps_mcp_generation` TRACE: an MPS generator (the structure aspect of the test language, generated by the
 * `lang.structure` generator), a fresh interpreted generator with one reduction rule, the
 * missing-trace and original-node cases, and the rendering of changes that no longer resolve.
 */
class JetBrainsMPSGenerationTraceIntegrationTest : McpIntegrationTestBase() {

    private val toolset = JetBrainsMPSGenerationMcpToolset()

    private fun trace(parameters: String): String =
        runTool(toolset) { it.mps_mcp_generation("TRACE", JsonOrText(parameters), maxInlineBytes = 1_000_000) }

    private fun baseLanguage() =
        checkNotNull(LanguageRegistry.getInstance(myProject.repository).getLanguage("jetbrains.mps.baseLanguage")) { "BaseLanguage is not deployed" }

    private fun baseConcept(name: String): SConcept =
        baseLanguage().identity.concepts.filterIsInstance<SConcept>().single { it.name == name }

    private fun baseNode(name: String) = MpsNode(baseConcept(name))

    private fun link(conceptName: String, role: String) = baseConcept(conceptName).containmentLinks.single { it.name == role }

    /** The project's transient models with their roots, for failure messages. */
    private fun transientDump(): String = readOnRepo {
        val provider = myProject.getComponent(TransientModelsProvider::class.java) ?: return@readOnRepo "no provider"
        provider.modules.joinToString("\n") { module ->
            module.moduleName + ": " + module.models.joinToString("; ") { model ->
                model.name.value + " [" + model.rootNodes.joinToString(", ") { "${it.concept.name} ${it.presentation} ${it.nodeId}" } + "]"
            }
        }
    }

    private fun make(parameters: String): JsonObject {
        val response = runTool(JetBrainsMPSNodeMcpToolset()) { it.mps_mcp_alter_nodes(MPSAlterOperation.MAKE, parameters) }
        val envelope = JsonParser.parseString(response).asJsonObject
        assertTrue("expected ok envelope: $response", envelope.get("ok").asBoolean)
        return parseDataObject(envelope.get("data"))
    }

    private fun steps(data: JsonObject) = data.getAsJsonArray("steps").map { it.asJsonObject }

    private fun changes(data: JsonObject) = steps(data).flatMap { step -> step.getAsJsonArray("changes").map { it.asJsonObject } }

    private fun templates(data: JsonObject) = changes(data).flatMap { change -> change.getAsJsonArray("templates").map { it.asJsonObject } }

    /** The transient models these tests keep must not outlive them, for memory and for later bare-name lookups. */
    @After
    fun dropTransientModels() {
        myProject.getComponent(TransientModelsProvider::class.java)?.removeAllTransient()
    }

    @Test
    fun `TRACE of a language aspect lists the rules, walks back from an output node and honours the options`() {
        val conceptRef = createConceptRoot("Traced")

        val (noTrace, records) = captureLogRecords { trace("""{"nodeReference":"$conceptRef","direction":"FORWARD"}""") }
        assertNoProblemsLogged(records)
        val missing = JsonParser.parseString(noTrace).asJsonObject
        assertEquals(noTrace, "NOT_FOUND", missing.get("code").asString)
        assertTrue(noTrace, missing.get("error").asString.contains("saveTransientModels:true"))

        val made = make("""{"models":["$structureModelRef"],"saveTransientModels":true}""")
        assertTrue("the make keeps a trace for the structure model: $made", made.getAsJsonObject("transientModels").getAsJsonArray("traceAvailableFor").size() > 0)

        val forward = expectOk(trace("""{"nodeReference":"$conceptRef","direction":"FORWARD"}"""))
        assertEquals("FORWARD", forward.get("direction").asString)
        assertEquals(conceptRef, forward.getAsJsonObject("node").get("reference").asString)
        assertFalse("an original-model node has no original input node", forward.has("originalInputNode"))
        assertEquals("CHANGE", forward.getAsJsonObject("options").get("groupBy").asString)
        val forwardSteps = steps(forward)
        assertTrue("the concept is transformed by some step: $forward", forwardSteps.isNotEmpty())
        assertTrue("empty steps are dropped by default: $forward", forwardSteps.all { it.getAsJsonArray("changes").size() > 0 })
        val structureModelName = readOnRepo { structureModel.name.longName }
        assertTrue(forwardSteps.all { it.get("input").asString.startsWith("$structureModelName@") && it.has("outputReference") })
        val rule = templates(forward).firstOrNull { it.get("role").asString == "RULE" }
        assertNotNull("the generator records the rule that fired: $forward", rule)
        assertTrue(rule.toString(), rule!!.get("generatorModule").asString.isNotEmpty() && rule.has("templateRoot") && rule.has("templateModel"))
        assertTrue(forward.getAsJsonArray("notes").any { it.asString == GenerationTraceOps.LIFECYCLE_NOTE })

        val output = changes(forward).map { it.getAsJsonObject("output") }.last { it.has("concept") }
        val backward = expectOk(trace("""{"nodeReference":"${output.get("reference").asString}","direction":"BACKWARD"}"""))
        assertTrue("an output node traces back: $backward", steps(backward).isNotEmpty())
        assertTrue("the walk back passes the rule: $backward", templates(backward).any { it.get("role").asString == "RULE" })
        assertFalse(backward.getAsJsonArray("notes").any { it.asString == GenerationTraceOps.BACKWARD_ORIGINAL_NOTE })

        val fromOriginal = expectOk(trace("""{"nodeReference":"$conceptRef","direction":"BACKWARD"}"""))
        assertEquals("BACKWARD from the original model has nothing to walk: $fromOriginal", 0, steps(fromOriginal).size)
        assertEquals(GenerationTraceOps.BACKWARD_ORIGINAL_NOTE, fromOriginal.getAsJsonArray("notes").first().asString)

        val byNode = expectOk(trace("""{"nodeReference":"$conceptRef","direction":"FORWARD","groupBy":"NODE"}"""))
        val groups = steps(byNode).flatMap { step -> step.getAsJsonArray("nodes").map { it.asJsonObject } }
        assertTrue("NODE grouping lists inputs with their outputs: $byNode", groups.isNotEmpty() && groups.all { it.has("input") && it.has("outputs") && it.has("templates") })

        val total = forward.get("changesTotal").asInt
        assumeTrue("truncation needs more than one change: $forward", total > 1)
        val truncatedResponse = trace("""{"nodeReference":"$conceptRef","direction":"FORWARD","maxChanges":1}""")
        val truncated = expectOk(truncatedResponse)
        assertTrue(truncated.get("truncated").asBoolean)
        assertEquals(1, truncated.get("changesReturned").asInt)
        assertEquals(total, truncated.get("changesTotal").asInt)
        assertEquals(1, changes(truncated).size)
        assertTrue(truncatedResponse, JsonParser.parseString(truncatedResponse).asJsonObject.getAsJsonArray("warnings").any { it.asString.contains("maxChanges") })
    }

    @Test
    fun `TRACE of an interpreted reduction rule names the rule, its mapping configuration and the input node`() {
        val fixture = ReductionFixture()
        val made = make("""{"modules":["${fixture.languageName}","${fixture.generatorName}"],"rebuild":true}""")
        assumeTrue("the language was not built and deployed: $made", made.get("success").asBoolean && made.get("runtimeReady").asBoolean)
        val thing = readOnRepo {
            LanguageRegistry.getInstance(myProject.repository).getLanguage(fixture.languageName)
                ?.identity?.concepts?.filterIsInstance<SConcept>()?.singleOrNull { it.name == "Thing" }
        }
        assumeTrue("the deployed language has no Thing concept", thing != null)

        val solution = createSolution()
        val model = createModel(solution, "${solution.moduleName}.sandbox")
        lateinit var inputRef: String
        executeCommand {
            (model as SModelInternal).addLanguage(MetaAdapterByDeclaration.getLanguage(fixture.language))
            (model as SModelInternal).addLanguage(baseLanguage().identity)
            // A root is copied, never reduced, so the Thing sits in a method body: class Holder { void run() { <Thing> } }
            val thingNode = MpsNode(thing!!)
            val body = baseNode("StatementList").apply { addChild(link("StatementList", "statement"), thingNode) }
            val method = baseNode("InstanceMethodDeclaration").apply {
                setProperty(SNodeUtil.property_INamedConcept_name, "run")
                addChild(link("InstanceMethodDeclaration", "returnType"), baseNode("VoidType"))
                addChild(link("InstanceMethodDeclaration", "body"), body)
                addChild(link("InstanceMethodDeclaration", "visibility"), baseNode("PublicVisibility"))
            }
            val holder = baseNode("ClassConcept").apply {
                setProperty(SNodeUtil.property_INamedConcept_name, "Holder")
                addChild(link("ClassConcept", "member"), method)
                addChild(link("ClassConcept", "visibility"), baseNode("PublicVisibility"))
            }
            model.addRootNode(holder)
            inputRef = PersistenceFacade.getInstance().asString(thingNode.reference)
        }
        val generated = make("""{"models":["${modelRefOf(model)}"],"rebuild":true,"saveTransientModels":true}""")
        assertTrue("the sandbox make keeps a trace: $generated", generated.getAsJsonObject("transientModels").getAsJsonArray("traceAvailableFor").size() > 0)

        val forward = expectOk(trace("""{"nodeReference":"$inputRef","direction":"FORWARD"}"""))
        val reduction = changes(forward).firstOrNull { change ->
            change.getAsJsonArray("templates").any { it.asJsonObject.get("reference")?.asString == fixture.ruleRef }
        }
        assertNotNull("the reduction rule is recorded: $forward\n${transientDump()}\nmake: $generated", reduction)
        val rule = reduction!!.getAsJsonArray("templates").map { it.asJsonObject }.single { it.get("reference").asString == fixture.ruleRef }
        assertEquals("RULE", rule.get("role").asString)
        assertEquals("Reduction_MappingRule", rule.get("concept").asString)
        assertEquals(fixture.mappingConfigurationRef, rule.getAsJsonObject("templateRoot").get("reference").asString)
        assertEquals(fixture.generatorName, rule.get("generatorModule").asString)
        assertEquals(fixture.generatorModelName, rule.get("templateModel").asString)
        val output = reduction.getAsJsonObject("output")
        assertEquals("the inline template produces a return statement: $reduction", "ReturnStatement", output.get("concept").asString)

        val backward = expectOk(trace("""{"nodeReference":"${output.get("reference").asString}","direction":"BACKWARD"}"""))
        assertTrue("the statement traces back to the rule: $backward", templates(backward).any { it.get("reference")?.asString == fixture.ruleRef })
        val thingId = inputRef.substringAfterLast('/')
        assertTrue(
            "BACKWARD lists the Thing (its transient copy keeps the node id) as the input: $backward",
            changes(backward).any { it.getAsJsonObject("input").get("reference")?.asString?.substringAfterLast('/') == thingId },
        )
        backward.getAsJsonObject("originalInputNode")?.let {
            assertEquals("the statement was generated from the Thing: $backward", inputRef, it.get("reference").asString)
        }
    }

    @Test
    fun `TRACE renders creations, deletions and nodes that no longer resolve`() {
        val conceptRef = createConceptRoot("Rendered")
        val rendered = readOnRepo {
            val node = resolveNodeRef(conceptRef)
            val gone = SNodePointer(structureModel.reference, PersistenceFacade.getInstance().createNodeId("4242424242"))
            val step = GenerationTraceOps.Step(structureModel.reference, structureModel.reference)
            step.changes[SNodePointer(structureModel.reference, null) to gone] = linkedSetOf<SNodeReference>(gone)
            step.changes[node.reference to SNodePointer(structureModel.reference, null)] = linkedSetOf<SNodeReference>(node.reference)
            val options = GenerationTraceOps.parseOptions(JsonParser.parseString("""{"direction":"FORWARD"}""").asJsonObject, GenTraceSettings())
            GenerationTraceOps.render(node, myProject.repository, listOf(step), options)
        }
        val (created, deleted) = changes(rendered)
        assertEquals("<no input>", created.getAsJsonObject("input").get("presentation").asString)
        assertFalse(created.getAsJsonObject("output").get("resolved").asBoolean)
        val unresolvedTemplate = created.getAsJsonArray("templates").single().asJsonObject
        assertEquals("UNKNOWN", unresolvedTemplate.get("role").asString)
        assertFalse(unresolvedTemplate.get("resolved").asBoolean)
        assertEquals(conceptRef, deleted.getAsJsonObject("input").get("reference").asString)
        assertEquals("<no output>", deleted.getAsJsonObject("output").get("presentation").asString)
        assertEquals("a structure-model node is no generator template", "UNKNOWN", deleted.getAsJsonArray("templates").single().asJsonObject.get("role").asString)
    }

    private fun renderSynthetic(parameters: String, vararg steps: GenerationTraceOps.Step, start: SNode): JsonObject = readOnRepo {
        val options = GenerationTraceOps.parseOptions(JsonParser.parseString(parameters).asJsonObject, GenTraceSettings())
        GenerationTraceOps.render(start, myProject.repository, steps.toList(), options)
    }

    private fun step() = GenerationTraceOps.Step(structureModel.reference, structureModel.reference)

    private fun gone(id: String): SNodeReference = SNodePointer(structureModel.reference, PersistenceFacade.getInstance().createNodeId(id))

    @Test
    fun `TRACE compacts templates to the innermost per root, groups by output walking BACKWARD and truncates at a step boundary`() {
        val conceptRef = createConceptRoot("Compacted", propertiesJson = """[{"name":"size","type":"string"}]""")
        val (root, property) = readOnRepo {
            val node = resolveNodeRef(conceptRef)
            node to node.children.single { it.concept.name == "PropertyDeclaration" }
        }
        val templatesStep = step().apply {
            changes[root.reference to gone("101")] = linkedSetOf(root.reference, property.reference, gone("102"))
        }
        val full = renderSynthetic("""{"direction":"FORWARD"}""", templatesStep, start = root)
        assertEquals(3, changes(full).single().getAsJsonArray("templates").size())
        val compacted = renderSynthetic("""{"direction":"FORWARD","compactTemplates":true}""", templatesStep, start = root)
        val kept = changes(compacted).single().getAsJsonArray("templates").map { it.asJsonObject }
        assertEquals("the unresolved template stays, the enclosing root goes: $kept", 2, kept.size)
        assertEquals(readOnRepo { PersistenceFacade.getInstance().asString(property.reference) }, kept.single { it.has("concept") }.get("reference").asString)
        assertTrue(kept.any { it.get("resolved")?.asBoolean == false })

        val merging = step().apply {
            changes[root.reference to gone("201")] = linkedSetOf(gone("901"))
            changes[property.reference to gone("201")] = linkedSetOf(gone("902"))
        }
        val byOutput = renderSynthetic("""{"direction":"BACKWARD","groupBy":"NODE"}""", merging, start = root)
        val group = steps(byOutput).single().getAsJsonArray("nodes").single().asJsonObject
        assertFalse("the output does not resolve: $group", group.getAsJsonObject("output").get("resolved").asBoolean)
        assertEquals(2, group.getAsJsonArray("inputs").size())
        assertEquals(2, group.getAsJsonArray("templates").size())
        assertEquals("one entry per node group", 1, byOutput.get("changesTotal").asInt)

        val second = step().apply { changes[gone("301") to gone("302")] = linkedSetOf(gone("903")) }
        val truncated = renderSynthetic("""{"direction":"FORWARD","maxChanges":1}""", templatesStep, second, start = root)
        assertEquals("the full first step only: $truncated", 1, steps(truncated).size)
        assertTrue(truncated.get("truncated").asBoolean)
        assertEquals(1, truncated.get("changesReturned").asInt)
        assertEquals(2, truncated.get("changesTotal").asInt)
        val notTruncated = renderSynthetic("""{"direction":"FORWARD","maxChanges":2}""", templatesStep, second, start = root)
        assertFalse(notTruncated.has("truncated"))
        assertEquals(2, steps(notTruncated).size)

        val nothing = renderSynthetic("""{"direction":"FORWARD"}""", start = root)
        assertEquals(GenerationTraceOps.NO_STEP_FORWARD_NOTE, nothing.getAsJsonArray("notes").first().asString)
        val transientStart = readOnRepo {
            val transientModel = myProject.getComponent(TransientModelsProvider::class.java)!!.modules.flatMap { it.models }.firstOrNull()
            transientModel?.rootNodes?.firstOrNull()
        }
        if (transientStart != null) {
            val nothingBack = renderSynthetic("""{"direction":"BACKWARD"}""", start = transientStart)
            assertEquals(GenerationTraceOps.NO_STEP_BACKWARD_NOTE, nothingBack.getAsJsonArray("notes").first().asString)
        }
        val originalBack = renderSynthetic("""{"direction":"BACKWARD"}""", start = root)
        assertEquals("an original node gets the original-model note instead", GenerationTraceOps.BACKWARD_ORIGINAL_NOTE, originalBack.getAsJsonArray("notes").first().asString)
        val empty = renderSynthetic("""{"direction":"FORWARD","includeEmptySteps":true}""", step(), start = root)
        assertEquals("an empty step is listed on request", 1, steps(empty).size)
    }

    @Test
    fun `TRACE rejects a missing node and bad options`() {
        val (missing, records) = captureLogRecords { trace("""{"nodeReference":"no.such.Node","direction":"FORWARD"}""") }
        assertNoProblemsLogged(records)
        assertEquals("NOT_FOUND", JsonParser.parseString(missing).asJsonObject.get("code").asString)
        assertMissingParameterKeys(trace("""{"direction":"FORWARD"}"""), listOf("nodeReference"))
        val conceptRef = createConceptRoot("Options")
        val badDirection = JsonParser.parseString(trace("""{"nodeReference":"$conceptRef","direction":"UP"}""")).asJsonObject
        assertEquals("INVALID_REQUEST", badDirection.get("code").asString)
        assertTrue(badDirection.get("error").asString.contains("direction"))
        val objectGroupBy = JsonParser.parseString(trace("""{"nodeReference":"$conceptRef","direction":"FORWARD","groupBy":{}}""")).asJsonObject
        assertEquals("INVALID_REQUEST", objectGroupBy.get("code").asString)
        assertTrue(objectGroupBy.get("error").asString.contains("groupBy"))
    }

    /**
     * A fresh language with a generator: a concept `Thing` extending BaseLanguage's `Statement`, and one mapping
     * configuration whose reduction rule turns a `Thing` into `return;` through an inline template. Not built yet.
     */
    private inner class ReductionFixture {
        val languageName = "test.trace${System.nanoTime()}"
        val language: Language
        val generatorName: String
        val generatorModelName: String
        val ruleRef: String
        val mappingConfigurationRef: String

        init {
            val dir = createDirInProject(languageName)
            var created: Language? = null
            executeCommand { created = LanguageProducer(myProject).withGenerator(true).create(languageName, dir) }
            language = checkNotNull(created)
            val structureRef = readOnRepo { modelRefOf(language.models.single { it.name.longName.endsWith(".structure") }) }
            val generatorModel = readOnRepo { language.generators.single().models.single { SModelStereotype.isGeneratorModel(it) } }
            generatorName = readOnRepo { language.generators.single().moduleName!! }
            generatorModelName = readOnRepo { generatorModel.name.value }
            expectOk(runTool {
                it.mps_mcp_alter_structure(
                    MPSStructureAlterOperation.CREATE_CONCEPTS,
                    """{"structureModelRef":"$structureRef","conceptsJson":[{"name":"Thing","extends":"jetbrains.mps.baseLanguage.structure.Statement"}]}""",
                )
            })
            val thingRef = readOnRepo {
                val model = PersistenceFacade.getInstance().createModelReference(structureRef).resolve(myProject.repository)!!
                PersistenceFacade.getInstance().asString(model.rootNodes.single { it.name == "Thing" }.reference)
            }
            val inserted = expectOk(runTool(JetBrainsMPSRootNodeMcpToolset()) {
                it.mps_mcp_insert_root_node_from_json(
                    modelRefOf(generatorModel),
                    JsonOrText(
                        """{"concept":"jetbrains.mps.lang.generator.structure.MappingConfiguration","properties":[{"name":"name","value":"main"}],
                           "children":[{"role":"reductionMappingRule","nodes":[{"concept":"jetbrains.mps.lang.generator.structure.Reduction_MappingRule",
                             "references":[{"role":"applicableConcept","target":"$thingRef"}],
                             "children":[{"role":"ruleConsequence","nodes":[{"concept":"jetbrains.mps.lang.generator.structure.InlineTemplate_RuleConsequence",
                               "children":[{"role":"templateNode","nodes":[{"concept":"jetbrains.mps.baseLanguage.structure.ReturnStatement"}]}]}]}]}]}]}""",
                    ),
                    dryRun = false,
                    responseDetail = "summary",
                )
            })
            mappingConfigurationRef = inserted.getAsJsonArray("roots").single().asJsonObject.get("reference").asString
            ruleRef = readOnRepo {
                val root = PersistenceFacade.getInstance().createNodeReference(mappingConfigurationRef).resolve(myProject.repository)!!
                PersistenceFacade.getInstance().asString(root.children.single { it.concept.name == "Reduction_MappingRule" }.reference)
            }
        }
    }
